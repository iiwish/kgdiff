//! `kgdiff completion <shell>`: completion scripts for bash, zsh and fish.
//!
//! The scripts are generated from the option tables of `args` and the descriptions of `help`,
//! so they cannot fall behind the options: a new option, value or subcommand appears in all
//! three. They complete options (long and short), the values of options that take one of a
//! fixed set, file names where a file is expected, and the subcommands. Pure: no I/O.

use std::fmt::Write as _;

use crate::args::{
    Completes, CompletionOption, HELP_TOPICS, HelpTopic, SUBCOMMANDS, Shell, completion_options,
};
use crate::help::option_description;

/// What the scripts say about a subcommand.
fn subcommand_description(name: &str) -> &'static str {
    match name {
        "apply" => "Apply a delta to a graph",
        "help" => "Show help",
        "completion" => "Print a shell completion script",
        _ => "",
    }
}

/// A command whose options the scripts list: its name on the command line (`diff` for
/// `kgdiff <before> <after>`, which has none) and its options with their descriptions.
struct Described {
    command: &'static str,
    options: Vec<(CompletionOption, &'static str)>,
}

fn described(command: &'static str, topic: HelpTopic) -> Described {
    Described {
        command,
        options: completion_options(topic)
            .into_iter()
            .map(|o| (o, option_description(topic, o.name).unwrap_or("")))
            .collect(),
    }
}

/// `kgdiff help` takes `--color` only; the rest of `completion`'s options are its own.
fn commands() -> [Described; 4] {
    let mut help = described("help", HelpTopic::Completion);
    help.options.retain(|(o, _)| o.name == "color");
    [
        described("diff", HelpTopic::Main),
        described("apply", HelpTopic::Apply),
        help,
        described("completion", HelpTopic::Completion),
    ]
}

/// The completion script of a shell.
pub fn completion_script(shell: Shell) -> String {
    let commands = commands();
    match shell {
        Shell::Bash => bash(&commands),
        Shell::Zsh => zsh(&commands),
        Shell::Fish => fish(&commands),
    }
}

// ─── bash ────────────────────────────────────────────────────────────────────

fn bash(commands: &[Described]) -> String {
    let mut out = String::from(
        r#"# bash completion for kgdiff. Generated by `kgdiff completion bash`.
#
#   source <(kgdiff completion bash)        # in ~/.bashrc, or
#   kgdiff completion bash > ~/.local/share/bash-completion/completions/kgdiff

_kgdiff_files() {
    local IFS=$'\n'
    compopt -o filenames 2>/dev/null
    COMPREPLY+=($(compgen -f -- "$cur"))
}

_kgdiff() {
    local cur prev cmd
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    # --option=value arrives as three words: --option, = and value.
    if [[ "$cur" == "=" ]]; then
        cur=""
    elif [[ "$prev" == "=" && $COMP_CWORD -ge 2 ]]; then
        prev="${COMP_WORDS[COMP_CWORD-2]}"
    fi
    cmd=diff
    if [[ $COMP_CWORD -gt 1 ]]; then
        case "${COMP_WORDS[1]}" in
"#,
    );
    let _ = writeln!(
        out,
        "            {}) cmd=\"${{COMP_WORDS[1]}}\" ;;",
        SUBCOMMANDS.join("|")
    );
    out.push_str("        esac\n    fi\n\n    case \"$cmd:$prev\" in\n");
    for c in commands {
        // Options with the same values share a branch, in the order of the first.
        let mut groups: Vec<(Completes, Vec<String>)> = Vec::new();
        for (o, _) in &c.options {
            if matches!(o.value, Completes::Nothing | Completes::OptionalFile) {
                continue;
            }
            let mut patterns = vec![format!("{}:--{}", c.command, o.name)];
            if let Some(s) = o.short {
                patterns.push(format!("{}:-{s}", c.command));
            }
            match groups.iter_mut().find(|(v, _)| *v == o.value) {
                Some((_, list)) => list.extend(patterns),
                None => groups.push((o.value, patterns)),
            }
        }
        for (value, patterns) in groups {
            let _ = writeln!(out, "        {})", patterns.join("|"));
            match value {
                Completes::Choices(choices) => {
                    let _ = writeln!(
                        out,
                        "            COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))",
                        choices.join(" ")
                    );
                }
                Completes::File => out.push_str("            _kgdiff_files\n"),
                _ => {}
            }
            out.push_str("            return ;;\n");
        }
    }
    out.push_str("    esac\n\n    if [[ \"$cur\" == -* ]]; then\n        case \"$cmd\" in\n");
    for c in commands {
        let mut words = Vec::new();
        for (o, _) in &c.options {
            words.push(format!("--{}", o.name));
            if let Some(s) = o.short {
                words.push(format!("-{s}"));
            }
        }
        let _ = writeln!(
            out,
            "            {}) COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")) ;;",
            c.command,
            words.join(" ")
        );
    }
    out.push_str("        esac\n        return\n    fi\n\n    case \"$cmd\" in\n");
    let _ = writeln!(
        out,
        "        help) [[ $COMP_CWORD -eq 2 ]] && COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")) ;;",
        HELP_TOPICS.join(" ")
    );
    let _ = writeln!(
        out,
        "        completion) [[ $COMP_CWORD -eq 2 ]] && COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")) ;;",
        Shell::ALL.join(" ")
    );
    let _ = writeln!(
        out,
        "        *)\n            [[ $COMP_CWORD -eq 1 ]] && COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n            _kgdiff_files ;;",
        SUBCOMMANDS.join(" ")
    );
    out.push_str("    esac\n}\n\ncomplete -F _kgdiff kgdiff\n");
    out
}

// ─── zsh ─────────────────────────────────────────────────────────────────────

/// Inside single quotes.
fn single_quoted(text: &str) -> String {
    text.replace('\'', r"'\''")
}

/// An `_arguments` description: between `[` and `]`, inside single quotes.
fn zsh_description(text: &str) -> String {
    single_quoted(&text.replace('\\', r"\\").replace(']', r"\]"))
}

/// The `_arguments` specs of an option: one for the long name, one for the short.
fn zsh_specs(o: &CompletionOption, description: &str) -> Vec<String> {
    let action = match o.value {
        Completes::Nothing => String::new(),
        Completes::Choices(choices) => format!(":{}:({})", o.name, choices.join(" ")),
        Completes::File => ":file:_files".to_owned(),
        Completes::OptionalFile => "::file:_files".to_owned(),
        Completes::Text => format!(":{}: ", o.name),
    };
    let takes_value = o.value != Completes::Nothing;
    let mut flags = vec![format!(
        "--{}{}",
        o.name,
        if takes_value { "=" } else { "" }
    )];
    if let Some(s) = o.short {
        flags.push(format!("-{s}{}", if takes_value { "+" } else { "" }));
    }
    let prefix = if o.repeatable {
        "*".to_owned()
    } else if let Some(s) = o.short {
        format!("(-{s} --{})", o.name)
    } else {
        String::new()
    };
    flags
        .iter()
        .map(|flag| format!("'{prefix}{flag}[{}]{action}'", zsh_description(description)))
        .collect()
}

fn zsh(commands: &[Described]) -> String {
    let mut out = String::from(
        r#"#compdef kgdiff
# zsh completion for kgdiff. Generated by `kgdiff completion zsh`.
#
#   kgdiff completion zsh > "${fpath[1]}/_kgdiff"   # then restart the shell, or
#   source <(kgdiff completion zsh)                 # in ~/.zshrc, after compinit

# The first argument is a command or the <before> file; a command only comes first.
_kgdiff_first() {
    if (( CURRENT != 2 )); then
        _files
        return
    fi
    _alternative \
"#,
    );
    let described: Vec<String> = SUBCOMMANDS
        .iter()
        .map(|name| format!("{name}\\:\"{}\"", subcommand_description(name)))
        .collect();
    let _ = writeln!(
        out,
        "        'commands:command:(({}))' \\\n        'files:file:_files'\n}}\n",
        single_quoted(&described.join(" "))
    );
    out.push_str("_kgdiff() {\n    local -a args\n    if (( CURRENT > 2 )); then\n        case ${words[2]} in\n");
    let positionals = |command: &str| match command {
        "apply" => "'1:graph:_files' '2:delta:_files'".to_owned(),
        "help" => format!("'1:topic:({})'", HELP_TOPICS.join(" ")),
        "completion" => format!("'1:shell:({})'", Shell::ALL.join(" ")),
        _ => "'1: :_kgdiff_first' '2:after:_files'".to_owned(),
    };
    let args = |c: &Described, indent: &str| {
        let mut text = format!("{indent}args=(\n");
        for (o, description) in &c.options {
            for spec in zsh_specs(o, description) {
                let _ = writeln!(text, "{indent}    {spec}");
            }
        }
        let _ = writeln!(text, "{indent})");
        let _ = writeln!(
            text,
            "{indent}_arguments -s -S $args {}",
            positionals(c.command)
        );
        text
    };
    for c in commands.iter().filter(|c| c.command != "diff") {
        let _ = writeln!(out, "            {})", c.command);
        out.push_str("                shift words\n                (( CURRENT-- ))\n");
        out.push_str(&args(c, "                "));
        out.push_str("                return ;;\n");
    }
    out.push_str("        esac\n    fi\n");
    if let Some(diff) = commands.iter().find(|c| c.command == "diff") {
        out.push_str(&args(diff, "    "));
    }
    out.push_str(
        r#"}

if [[ "${funcstack[1]}" == "_kgdiff" ]]; then
    _kgdiff "$@"
else
    compdef _kgdiff kgdiff
fi
"#,
    );
    out
}

// ─── fish ────────────────────────────────────────────────────────────────────

/// Inside fish's single quotes, where only `\` and `'` are special.
fn fish_quoted(text: &str) -> String {
    text.replace('\\', r"\\").replace('\'', r"\'")
}

fn fish(commands: &[Described]) -> String {
    let mut out = String::from(
        r"# fish completion for kgdiff. Generated by `kgdiff completion fish`.
#
#   kgdiff completion fish > ~/.config/fish/completions/kgdiff.fish

# The command the line is in: a subcommand when it is the first argument, else `diff`.
function __kgdiff_command
    set -l tokens (commandline -opc)
    if test (count $tokens) -ge 2
        switch $tokens[2]
",
    );
    let _ = writeln!(out, "            case {}", SUBCOMMANDS.join(" "));
    out.push_str(
        r"                echo $tokens[2]
                return
        end
    end
    echo diff
end

function __kgdiff_in
    test (__kgdiff_command) = $argv[1]
end

function __kgdiff_first
    test (count (commandline -opc)) -eq 1
end

complete -c kgdiff -e
",
    );
    for name in SUBCOMMANDS {
        let _ = writeln!(
            out,
            "complete -c kgdiff -n __kgdiff_first -a {name} -d '{}'",
            fish_quoted(subcommand_description(name))
        );
    }
    let _ = writeln!(
        out,
        "complete -c kgdiff -n '__kgdiff_in help' -f -a '{}'",
        HELP_TOPICS.join(" ")
    );
    let _ = writeln!(
        out,
        "complete -c kgdiff -n '__kgdiff_in completion' -f -a '{}'",
        Shell::ALL.join(" ")
    );
    for c in commands {
        out.push('\n');
        for (o, description) in &c.options {
            let _ = write!(
                out,
                "complete -c kgdiff -n '__kgdiff_in {}' -l {}",
                c.command, o.name
            );
            if let Some(s) = o.short {
                let _ = write!(out, " -s {s}");
            }
            match o.value {
                Completes::Nothing | Completes::OptionalFile => {}
                Completes::Choices(choices) => {
                    let _ = write!(out, " -x -a '{}'", choices.join(" "));
                }
                Completes::File => out.push_str(" -r -F"),
                Completes::Text => out.push_str(" -x"),
            }
            if !description.is_empty() {
                let _ = write!(out, " -d '{}'", fish_quoted(description));
            }
            out.push('\n');
        }
    }
    out
}
